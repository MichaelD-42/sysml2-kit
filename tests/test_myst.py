import unittest

from sysml2kit.myst import to_myst

NEEDS = {
    "LI-2": {
        "id": "LI-2",
        "type": "interface",
        "title": "drive",
        "content": "Torque for F\\_1.",
        "medium": "data",
        "connects": ["LC-2", "LC-3"],
        "owned_by": ["LC-1"],
        "satisfies": [],
    },
    "LC-2": {
        "id": "LC-2",
        "type": "component",
        "title": "powertrain",
        "content": "",
        "connects": [],
        "owned_by": ["LC-1"],
    },
}


class MystTest(unittest.TestCase):
    def test_default_writes_every_link(self):
        text = to_myst(NEEDS)
        self.assertIn(
            ":::{interface} drive\n:id: LI-2\n:connects: LC-2,LC-3\n:owned_by: LC-1\n\nTorque for F_1.\n:::",
            text,
        )
        self.assertNotIn(":satisfies:", text)
        self.assertNotIn(":medium:", text)

    def test_links_merge_and_fields_rename(self):
        need = {
            "id": "F_2",
            "type": "function",
            "title": "t",
            "content": "",
            "owned_by": ["F_1"],
            "part_of": ["P_1", "F_1"],
            "v": "both",
        }
        text = to_myst(
            {"F_2": need},
            {
                "links": {"owned_by": "part_of", "part_of": "part_of"},
                "fields": {"v": "variant"},
            },
        )
        self.assertIn(":id: F_2\n:variant: both\n:part_of: F_1,P_1\n:::", text)

    def test_mapping_renames_and_selects(self):
        mapping = {
            "types": {"component": "lcomp"},
            "links": {"connects": "connects", "owned_by": "part_of"},
            "fields": ["medium"],
        }
        text = to_myst(NEEDS, mapping, "x.json")
        self.assertTrue(text.startswith("% Generated by sysml2kit from x.json."))
        self.assertIn(":::{lcomp} powertrain\n:id: LC-2\n:part_of: LC-1\n:::", text)
        self.assertIn(
            ":id: LI-2\n:medium: data\n:connects: LC-2,LC-3\n:part_of: LC-1\n", text
        )
        self.assertLess(text.index("LC-2"), text.index(":id: LI-2"))


if __name__ == "__main__":
    unittest.main()
