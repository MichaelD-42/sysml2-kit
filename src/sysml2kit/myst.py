"""Bridge needs (`sysml2kit needs` output) -> MyST need directives, for a project that keeps its
needs in Markdown files rather than importing a needs.json."""

# shortcut: a doc text holding a line of only `:::` would end the directive early; fence longer if that happens


def to_myst(needs, mapping=None, source=""):
    """One `:::{type}` directive per need, in id order.

    `mapping["types"]` renames need types and `mapping["links"]` link types; when `links` is
    given, only the links it names are written. `mapping["fields"]` lists the fields to write."""
    mapping = mapping or {}
    types = mapping.get("types", {})
    links = mapping.get("links")
    fields = mapping.get("fields", [])
    out = [
        f"% Generated by sysml2kit from {source or 'the model'}. Do not edit; change the model.",
        "",
    ]
    for need_id in sorted(needs):
        need = needs[need_id]
        out.append(f":::{{{types.get(need['type'], need['type'])}}} {need['title']}")
        out.append(f":id: {need_id}")
        for field in fields:
            if need.get(field) not in (None, "", [], False):
                out.append(f":{field}: {need[field]}")
        for link, name in (
            links or {k: k for k, v in need.items() if isinstance(v, list)}
        ).items():
            if need.get(link):
                out.append(f":{name}: {','.join(need[link])}")
        if need.get("content"):
            out += ["", need["content"]]
        out += [":::", ""]
    return "\n".join(out)
